// Подключаем библиотеку для ввода-вывода
#include <stdio.h>

// Главная функция программы
int main() {
    // Объявляем массив из 10 чисел
    int arr[10] = {64, 34, 25, 12, 22, 11, 90, 88, 45, 50};
    
    // Выводим исходный массив
    printf("Исходный массив: ");
    for (int i = 0; i < 10; i++) {
        printf("%d ", arr[i]);
    }
    printf("\n");
    
    // СОРТИРОВКА (метод пузырька)
    // Внешний цикл — проходы по массиву
    for (int i = 0; i < 9; i++) {
        // Внутренний цикл — сравнение соседних элементов
        for (int j = 0; j < 9 - i; j++) {
            // Если текущий элемент больше следующего
            if (arr[j] > arr[j + 1]) {
                // МЕНЯЕМ ИХ МЕСТАМИ
                int temp = arr[j];        // сохраняем текущий в temp
                arr[j] = arr[j + 1];      // записываем следующий в текущий
                arr[j + 1] = temp;        // записываем temp в следующий
            }
        }
    }
    
    // Выводим отсортированный массив
    printf("Отсортированный массив: ");
    for (int i = 0; i < 10; i++) {
        printf("%d ", arr[i]);
    }
    printf("\n");
    
    return 0;  // программа завершилась успешно
}
