#include <stdio.h>

int main() {
    // 1. Объявляем и инициализируем массив из 5 чисел
    int arr[] = {64, 25, 12, 22, 11};
    int n = 5; // Количество элементов

    printf("Исходный массив:\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]); // Выводим каждое число
    }
    printf("\n");

    // 2. Сортировка методом "Пузырька" (Bubble Sort)
    // Внешний цикл проходит по массиву
    for (int i = 0; i < n - 1; i++) {
        // Внутренний цикл сравнивает соседние элементы
        for (int j = 0; j < n - i - 1; j++) {
            // Если левый элемент больше правого, меняем их местами
            if (arr[j] > arr[j + 1]) {
                int temp = arr[j];      // Сохраняем левый во временную переменную
                arr[j] = arr[j + 1];    // Переносим правый на место левого
                arr[j + 1] = temp;      // Переносим сохраненный левый на место правого
            }
        }
    }

    printf("Отсортированный массив:\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }
    printf("\n");

    return 0; // Завершение программы
}
